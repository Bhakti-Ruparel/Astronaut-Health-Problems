CREATE UNIQUE INDEX IF NOT EXISTS health_telemetry_event_id_uidx
    ON health_telemetry (event_id);
CREATE INDEX IF NOT EXISTS health_telemetry_astronaut_recorded_idx
    ON health_telemetry (astronaut_id, recorded_at DESC);
CREATE INDEX IF NOT EXISTS health_telemetry_user_live_idx
    ON health_telemetry (user_id, recorded_at DESC);

CREATE TABLE IF NOT EXISTS astro_reference_telemetry (
    event_id UUID PRIMARY KEY,
    astronaut_id TEXT NOT NULL,
    recorded_at TIMESTAMPTZ NOT NULL,
    source TEXT NOT NULL,
    heart_rate_bpm DOUBLE PRECISION NOT NULL,
    spo2_percent DOUBLE PRECISION NOT NULL,
    systolic_bp DOUBLE PRECISION NOT NULL,
    diastolic_bp DOUBLE PRECISION NOT NULL,
    body_temperature_c DOUBLE PRECISION NOT NULL,
    respiratory_rate DOUBLE PRECISION NOT NULL,
    ecg_heart_rate_bpm DOUBLE PRECISION NOT NULL,
    activity_level DOUBLE PRECISION NOT NULL,
    sleep_hours DOUBLE PRECISION NOT NULL,
    body_weight_kg DOUBLE PRECISION NOT NULL,
    radiation_exposure_msv DOUBLE PRECISION NOT NULL,
    anomaly_pred SMALLINT NOT NULL CHECK (anomaly_pred IN (-1, 1)),
    anomaly_score DOUBLE PRECISION NOT NULL,
    overall_status TEXT NOT NULL CHECK (overall_status IN ('NORMAL', 'ANOMALY')),
    anomalous_features JSONB NOT NULL DEFAULT '[]'::jsonb,
    raw_payload JSONB NOT NULL
);

CREATE INDEX IF NOT EXISTS astro_reference_telemetry_astronaut_recorded_idx
    ON astro_reference_telemetry (astronaut_id, recorded_at DESC);

CREATE TABLE IF NOT EXISTS astronaut_web_accounts (
    auth_user_id TEXT PRIMARY KEY,
    astronaut_id TEXT NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
